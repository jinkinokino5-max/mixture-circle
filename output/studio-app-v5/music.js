/* =====================================================================
   music.js — STUDIO PULSE II（v5）の「音楽そのもの」の定義
   ---------------------------------------------------------------------
   カード = ROLE（曲の中で何をするか）× INSTRUMENT（何の音でするか）
            × VARIATION（その楽器で何を弾くか）。

   全パートが共有する土台（ひとつの調・4小節の進行・ひとつのグルーヴ）は
   engine 側が握るので、何と何を重ねても必ず調和する。
   ---------------------------------------------------------------------
   ■ v5.1 でいちばん大きく変えたところ ： バリエーション

   「ギター1／ギター2／ギター3」のように、ひとつの楽器に3つの弾き方を
   用意した。40楽器 × 3 ＝ **120枚**。

   3つはランダムな別パターンではなく、**役割がはっきり違う**：

     変化1「基本」 … その楽器の代表的な弾き方。ふつうはこれ
     変化2「余白」 … 音数が少なく、音符が長い。すでに賑やかな音の
                     **下に敷く**ためのもの
     変化3「刻み」 … 音数が多く、音符が短い。すでに疎な音の
                     **上に乗せる**ためのもの

   これは飾りではなく、v5 でいちばん困っていた
   「重ねるほど団子になる」を正面から解く仕掛け。
   いま鳴っているものが賑やかなら 2 を、寂しいなら 3 を選べばよい。

   ■ 音量について（重要）

   sound（音色・音量・帯域）は **楽器ごとに1つだけ** 定義し、
   バリエーションはそれを共有する。だから
   「ギター1は良いけどギター3だけ妙に大きい」ということが起きない。

   さらに v5 では samples.js が音源の録音レベルを実測してそろえるので、
   ここの gain は「**この楽器をどのくらい前に出したいか**」だけを意味する。
   ROLE ごとにほぼ同じ数値が並び、ズレていたら意図的な差、と読める。

   ただし「音数が多い変化3は、同じ gain でも大きく聞こえる」ぶんは
   gain では吸収できないので、**変化3は各音の v（強さ）を控えめに**
   書いてある。この釣り合いは実際に音を書き出して測って調整した。
   ---------------------------------------------------------------------
   このファイルは「データと音楽の理屈」だけを持つ。
   音を鳴らす仕組み（Tone.js）は app.js 側にある。
   ===================================================================== */

/* ============ 1. 音の名前 ============ */
const NOTE_NAMES = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'];

/* 半音の通し番号 → 'D#4' のような音名。オクターブ4のCが60（MIDIと同じ） */
function midiToName(m) {
  const i = ((m % 12) + 12) % 12;
  return NOTE_NAMES[i] + (Math.floor(m / 12) - 1);
}
/* オクターブ番号と「Cからの半音数」から通し番号を作る */
function midiOf(oct, semi) { return (oct + 1) * 12 + semi; }

/* Cナチュラルマイナー（＝E♭メジャー）。全カードがこの7音の世界にいる */
const SCALE = [0, 2, 3, 5, 7, 8, 10];
function scaleSemi(deg) {
  const i = ((deg % 7) + 7) % 7;
  return SCALE[i] + 12 * Math.floor(deg / 7);
}

