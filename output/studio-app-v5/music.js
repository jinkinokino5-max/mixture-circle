/* ============ 7. 楽器 × バリエーション → カード（120枚）============
   カードID は '<楽器ID>-<番号>'（例 'melody-eguitar-2'）。
   RFID のカード1枚 ＝ このID1つ、という対応になる。
   sound は楽器のものをそのまま使い、variant が set / oct / drive を
   持っていたときだけ、その項目を差し替えたコピーを作る。            */
const CARDS = {};
const CARD_ORDER = {};

ROLE_ORDER.forEach(rk => {
  CARD_ORDER[rk] = [];
  INSTRUMENT_ORDER[rk].forEach(instId => {
    const inst = INSTRUMENTS[instId];
    inst.variants.forEach((va, i) => {
      const id = `${instId}-${i + 1}`;
      /* 上書きがあるものだけ sound のコピーを作る（無ければ共有＝音量も共有）。
         trim は「バリエーション間の音量をそろえるためだけ」の小さな補正。
         音数の多い変化3は同じ gain でも大きく聞こえてしまうので、その差を
         打ち消す。値は書き出して測った実測から決めていて、手で盛るための
         ものではない（だから ±6dB を超える値は検証で弾いている）。      */
      const over = {};
      ['set', 'oct', 'drive', 'hp', 'lp'].forEach(k => { if (k in va) over[k] = va[k]; });
      if (va.trim) over.gain = inst.sound.gain + va.trim;
      const sound = Object.keys(over).length ? Object.assign({}, inst.sound, over) : inst.sound;

      CARDS[id] = {
        inst: instId, n: i + 1,
        label: inst.label, tag: va.tag,
        sound,
        pat: va.pat, patB: va.patB,
        drum: va.drum, drumB: va.drumB,
      };
      CARD_ORDER[rk].push(id);
    });
  });
});

/* drumB は差分だけ書けばよいように、ここで drum とマージしておく */
Object.values(CARDS).forEach(c => {
  if (c.drum && c.drumB) c._drumB = Object.assign({}, c.drum, c.drumB);
});

/* ============ 8. 小節ごとのパターン切り替え ============
   4小節でひと回りするので、その4小節目（bar % 4 === 3）だけ
   patB / drumB があればそちらを使う。「ひと息つく／畳みかける」の一手。 */
function isVariantBar(bar) { return ((bar % 4) + 4) % 4 === 3; }
function patternAt(card, bar) { return (card.patB && isVariantBar(bar)) ? card.patB : card.pat; }
function drumAt(card, bar)    { return (card._drumB && isVariantBar(bar)) ? card._drumB : card.drum; }

/* ============ 9. ひとつの音の高さを決める ============
   同じパターンでも ROLE によって音の求め方が変わる：
     bass  → ルート中心（bassName）
     それ以外 → コード構成音（toneName）                            */
function resolveNotes(role, chord, ev, oct, lift) {
  const list = Array.isArray(ev.d) ? ev.d : [ev.d];
  return list.map(d => {
    if (d && typeof d === 'object' && 'sd' in d) return scaleName(chord, d.sd + lift, oct + (ev.o || 0));
    if (role === 'bass') return bassName(chord, d, oct + (ev.o || 0));
    return toneName(chord, d + lift, oct + (ev.o || 0));
  });
}
